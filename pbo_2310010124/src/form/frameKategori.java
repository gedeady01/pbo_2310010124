    private void tabelKategoriMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelKategoriMouseClicked
        int baris = tabelKategori.getSelectedRow();
        String id = tabelKategori.getValueAt(baris, 0).toString();
        String nm_kategori = tabelKategori.getValueAt(baris, 1).toString();
        String keterangan = tabelKategori.getValueAt(baris, 2).toString();
        
        txtIdKategori.setText(id);
        txtNamaKategori.setText(nm_kategori);
        txtKeterangan.setText(keterangan);
        objekku.loadData(tabelKategori, "SELECT * FROM kategori");
    }//GEN-LAST:event_tabelKategoriMouseClicked

    private void txtCariKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtCariKeyReleased
        try {
            String c = txtCari.getText();
            String cari = "SELECT * FROM kategori WHERE id_kategori like '%"+c+"%'" + 
                    "or nama_kategori like '%"+c+"%' or keterangan like '%"+c+"%' ";
            objekku.loadData(tabelKategori, cari);
        } catch (Exception e) {
            System.out.print(e);
        }
    }//GEN-LAST:event_txtCariKeyReleased

