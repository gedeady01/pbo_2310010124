    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try {
            objekku.simpanKategoriPRT(txtIdKategori.getText(),
                    txtNamaKategori.getText(),
                    txtKeterangan.getText());
            if (objekku.validasi == true){
                txtNamaKategori.setText(objekku.var_nm_kategori);
                txtKeterangan.setText(objekku.var_keterangan);
            }
            objekku.loadData(tabelKategori, "SELECT * FROM kategori");
        } catch (Exception e) {
            
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if(
               txtIdKategori.getText().isEmpty() || 
               txtNamaKategori.getText().isEmpty() || 
               txtKeterangan.getText().isEmpty()
               ){
               JOptionPane.showMessageDialog(null, "Silahkan Pilih Data Terlebih Dahulu");
               tabelKategori.requestFocus();
            }else{
               objekku.ubahKategoriPRT(txtIdKategori.getText(), 
                       txtNamaKategori.getText(), 
                       txtKeterangan.getText());
                objekku.loadData(tabelKategori, "SELECT * FROM kategori");
            }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if(
               txtIdKategori.getText().isEmpty() || 
               txtNamaKategori.getText().isEmpty() || 
               txtKeterangan.getText().isEmpty()
                    ) {
                JOptionPane.showMessageDialog(null, "Silahkan Pilih Data Terlebih Dahulu");
                tabelKategori.requestFocus();
            }else{
                objekku.hapusKategoriPRT(txtIdKategori.getText());
                txtIdKategori.setText(null);
                txtNamaKategori.setText(null);
                txtKeterangan.setText(null);
            }
        objekku.loadData(tabelKategori, "SELECT * FROM kategori");
    }//GEN-LAST:event_btnHapusActionPerformed

