    private void txtCariKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtCariKeyReleased
        try {
            String c = txtCari.getText();
            String cari = "SELECT * FROM wilayah WHERE id_wilayah like '%"+c+"%'" + 
                    "or nama_kecamatan like '%"+c+"%' or nama_kelurahan like '%"+c+"%' or kode_pos like '%"+c+"%' ";
            objekku.loadData(tabelWilayah, cari);
        } catch (Exception e) {
            System.out.print(e);
        }
    }//GEN-LAST:event_txtCariKeyReleased

    private void tabelWilayahMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelWilayahMouseClicked
        int baris = tabelWilayah.getSelectedRow();
        String id_wilayah = tabelWilayah.getValueAt(baris, 0).toString();
        String nm_kecamatan = tabelWilayah.getValueAt(baris, 1).toString();
        String nm_kelurahan = tabelWilayah.getValueAt(baris, 2).toString();
        String kode_pos = tabelWilayah.getValueAt(baris, 2).toString();
        
        txtIdWilayah.setText(id_wilayah);
        txtNamaKecamatan.setText(nm_kecamatan);
        txtNamaKelurahan.setText(nm_kelurahan);
        txtKodePos.setText(kode_pos);
        objekku.loadData(tabelWilayah, "SELECT * FROM wilayah");
    }//GEN-LAST:event_tabelWilayahMouseClicked

