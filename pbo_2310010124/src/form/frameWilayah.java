    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try {
            objekku.simpanWilayahPRT(txtIdWilayah.getText(),
                    txtNamaKecamatan.getText(),
                    txtNamaKelurahan.getText(),
                    txtKodePos.getText());
            if (objekku.validasi == true){
                txtNamaKecamatan.setText(objekku.var_nm_kecamatan);
                txtNamaKelurahan.setText(objekku.var_nm_kelurahan);
                txtKodePos.setText(objekku.var_kode_pos);
            }
            objekku.loadData(tabelWilayah, "SELECT * FROM wilayah");
        } catch (Exception e) {
            
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if(
               txtIdWilayah.getText().isEmpty() || 
               txtNamaKecamatan.getText().isEmpty() || 
               txtNamaKelurahan.getText().isEmpty() ||
               txtKodePos.getText().isEmpty()
               ){
               JOptionPane.showMessageDialog(null, "Silahkan Pilih Data Terlebih Dahulu");
               tabelWilayah.requestFocus();
            }else{
               objekku.ubahWilayahPRT(txtIdWilayah.getText(), 
                       txtNamaKecamatan.getText(), 
                       txtNamaKelurahan.getText(),
                       txtKodePos.getText());
                objekku.loadData(tabelWilayah, "SELECT * FROM wilayah");
            }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if(
               txtIdWilayah.getText().isEmpty() || 
               txtNamaKecamatan.getText().isEmpty() || 
               txtNamaKelurahan.getText().isEmpty() ||
               txtKodePos.getText().isEmpty()
                    ) {
                JOptionPane.showMessageDialog(null, "Silahkan Pilih Data Terlebih Dahulu");
                tabelWilayah.requestFocus();
            }else{
                objekku.hapusWilayahPRT(txtIdWilayah.getText());
                txtIdWilayah.setText(null);
                txtNamaKecamatan.setText(null);
                txtNamaKelurahan.setText(null);
                txtKodePos.setText(null);
            }
        objekku.loadData(tabelWilayah, "SELECT * FROM wilayah");
    }//GEN-LAST:event_btnHapusActionPerformed

